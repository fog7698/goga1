const WHITELIST = Array.from({ length: 3 }, (_, i) => `Белый список • Обход блокировок #${i + 1}`);

function formatExpiry(expiresAt) {
  if (!expiresAt) return null;
  const d = new Date(expiresAt.replace(' ', 'T') + 'Z');
  if (Number.isNaN(d.getTime())) return null;
  return d.toLocaleDateString('ru-RU', { day: '2-digit', month: '2-digit', year: 'numeric' });
}

/** `expiresAt` (SQLite `datetime('now')` string, UTC) is embedded as a read-only info entry
 * at the top of the location list so it shows inside Happ/INCY's own server picker. */
function subscriptionBase64(uuid, expiresAt) {
  const names = [...LOCATIONS, ...LTE_BYPASS, ...WHITELIST];
  // H1cloud's 3x-ui REALITY servers are the only transport confirmed working on Russian mobile
  // carriers (see the comment above H1_SERVERS) - route every displayed location through them,
  // round-robin, whenever at least one is configured. CF_HOST/VPN_HOST stay as the fallback path
  // (Wi-Fi-only, via vlessLink) for as long as VPN_H1_SERVERS is unset.
  const entries = H1_SERVERS.length
    ? names.map((n, i) => h1Link(i, n))
    : names.map((n) => vlessLink(uuid, n));
  const expiryLabel = formatExpiry(expiresAt);
  if (expiryLabel) {
    entries.unshift(H1_SERVERS.length ? h1Link(0, `⏳ Подписка активна до ${expiryLabel}`) : vlessLink(uuid, `⏳ Подписка активна до ${expiryLabel}`));
  }
  return Buffer.from(entries.join('\n'), 'utf8').toString('base64');
}

